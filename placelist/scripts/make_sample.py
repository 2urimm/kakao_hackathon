def make_folders_csv(places):
    by_id = {p["place_id"]: p for p in places}
    rows = []
    for fid, title, owner, subs, items in FOLDERS:
        for pid, designer, memo, saved in items:
            p = by_id[pid]
            rows.append({
                "folder_id": fid, "folder_title": title, "owner": owner,
                "subscribers": subs, "place_name": p["name"],
                "kakao_place_id": p["kakao_place_id"],
                "address": f"서울 마포구/서대문구 {p['공통']['지역']}",
                "memo": memo, "saved_at": saved, "designer": designer,
            })
    return rows

