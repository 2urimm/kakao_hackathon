KAKAO_CATEGORY = {"음식점": "음식점", "카페": "음식점 > 카페", "미용": "서비스,산업 > 미용 > 미용실"}

def make_places():
    out = []
    for i, (pid, name, cat, region, price, moods, purposes, extra) in enumerate(PLACES):
        lat, lng = REGIONS[region]
        out.append({
            "place_id": pid,
            "kakao_place_id": f"SAMPLE{1000 + i}",
            "name": name,
            "업종": cat,
            "kakao_category": KAKAO_CATEGORY[cat],
            "lat": round(lat + random.uniform(-0.004, 0.004), 6),
            "lng": round(lng + random.uniform(-0.004, 0.004), 6),
            "공통": {"지역": region, "가격대": price, "분위기": moods, "목적": purposes},
            "특화": extra,
        })
    return out

